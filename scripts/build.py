#!/usr/bin/env python3
"""Build the single-file Open WebUI Function from the package sources."""

import argparse
import ast
import hashlib
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "src" / "google_agent_platform_pipe"
OUTPUT = ROOT / "dist" / "google_agent_platform.py"
PYPROJECT = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
PROJECT = PYPROJECT["project"]
OPEN_WEBUI = PYPROJECT["tool"]["open-webui"]
MODULES = (
    "config.py",
    "models.py",
    "messages.py",
    "files.py",
    "tools.py",
    "client.py",
    "responses.py",
    "grounding.py",
    "agent.py",
    "pipe.py",
)
PLUGIN_HEADER = f'''"""
title: Google Agent Platform
author: {PROJECT["authors"][0]["name"]}
author_url: {OPEN_WEBUI["author_url"]}
project_url: {PROJECT["urls"]["Repository"]}
version: {PROJECT["version"]}
license: {PROJECT["license"]}
description: Native Google Agent Platform models with streaming, original-file input, Google Search, reasoning, usage, and tool calling.
"""
'''


def module_body(path: Path) -> str:
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(path))
    lines = source.splitlines(keepends=True)

    for node in tree.body:
        is_internal_import = isinstance(node, ast.ImportFrom) and (
            node.level > 0
            or (node.module or "").startswith("google_agent_platform_pipe")
        )
        if is_internal_import:
            for index in range(node.lineno - 1, node.end_lineno):
                lines[index] = ""

    return "".join(lines).strip() + "\n"


def build_content() -> str:
    sources = [(name, (SOURCE_DIR / name).read_bytes()) for name in MODULES]
    digest = hashlib.sha256(b"".join(content for _, content in sources)).hexdigest()[
        :12
    ]
    sections = [
        PLUGIN_HEADER.rstrip(),
        "",
        "# Generated by scripts/build.py; edit src/google_agent_platform_pipe instead.",
        f"# Source digest: {digest}",
    ]
    for name, _ in sources:
        sections.extend(
            ("", f"# --- {name} ---", "", module_body(SOURCE_DIR / name).rstrip())
        )
    content = "\n".join(sections) + "\n"
    compile(content, str(OUTPUT), "exec")
    return content


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the committed distribution is missing or stale.",
    )
    args = parser.parse_args()
    content = build_content()

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run scripts/build.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Built {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
